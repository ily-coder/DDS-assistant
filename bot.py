def get_keyboard():

    keyboard = VkKeyboard(one_time=False)

    keyboard.add_button(
        "📝 Задать вопрос",
        color=VkKeyboardColor.PRIMARY
    )

    keyboard.add_line()

    keyboard.add_openlink_button(
        "🆘 Техподдержка",
        SUPPORT_URL
    )

    return keyboard.get_keyboard()

